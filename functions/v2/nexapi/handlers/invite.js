const { embed } = require('#functions/v2/nexapi/compat');
const { devId: devID } = require('#config/core/discord');
const { client } = require('#bot');


module.exports = {
	async execute(interaction) {
		if (interaction.user.id == devID) {
			const guildId = interaction.options.getString("id");

			const guildArray = await client.cluster.broadcastEval(async (c, { guildId }) => {
				const guild = c.guilds.cache.get(guildId);
				if (guild) {
					const invite = await guild.systemChannel.createInvite({
						maxAge: 86400, // Time to live in seconds (86400 = 1 day, 0 = infinite)
						maxUses: 1,    // Maximum times the invite can be used (0 = infinite)
						unique: true,  // Creates a unique link every time
						reason: 'Generated by Bot'
					});
					return invite; // Indicate that the message was sent
				}
				return false; // Indicate that the message was not sent by this shard
			}, { context: { guildId } }); // Pass the channelId as context
			console.log(guildArray);

			let inviteURL = false;
			for(let i = 0; i < guildArray.length; i++){
				if(guildArray[i] !== false){
					inviteURL = guildArray[i];
				}
			}

			// Send reply
			let embeds = await embed("Dev Invite", `Invite URL: ${inviteURL.url}.`, null, null);
			if (!inviteURL) {
				embeds = await embed("Dev Invite", `The invite cannot be made.`, null, null);
			}
			await interaction.reply({
				embeds: [embeds]
			});
		} else {

			// Send reply
			const embeds = await embed("Dev Invite", `You do not have permission to use this command.`, null, null)
			await interaction.reply({
				embeds: [embeds]
			});
		}
	},
};
